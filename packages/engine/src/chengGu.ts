export function calculateChengGu(
  yearStem: TianGan, yearBranch: DiZhi,
  lunarMonth: number, lunarDay: number,
  hourBranch: DiZhi,
): ChengGu {
  const yearKey = `${yearStem}${yearBranch}`;
  const yw = YEAR_WEIGHT[yearKey] ?? 0;
  const mw = MONTH_WEIGHT[lunarMonth] ?? 0;
  const dw = DAY_WEIGHT[lunarDay] ?? 0;
  const hw = HOUR_WEIGHT[hourBranch] ?? 0;
  const totalQian = Math.round((yw + mw + dw + hw) * 10);
  const liang = Math.floor(totalQian / 10);
  const qian = totalQian % 10;
  const weight = qian === 0 ? `${liang}两` : `${liang}两${qian}钱`;
  const description = FATE_TABLE[weight] ?? '';
  return { weight, totalQian, description };
}
