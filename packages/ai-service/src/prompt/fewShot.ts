/** 组装少样本为 messages 格式(供直接拼接到对话历史前) */
export function toMessages(examples = FEWSHOT_EXAMPLES) {
  return examples.flatMap((e) => [
    { role: 'user' as const, content: e.user },
    { role: 'assistant' as const, content: e.assistant },
  ]);
}
